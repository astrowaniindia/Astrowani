// astrowani-backend/src/backupStorage.js
//
// Cloudflare R2 for DATABASE BACKUPS, through its S3-compatible API, signed with aws4fetch
// (SigV4, no AWS SDK) — the same approach as src/objectStorage.js.
//
// WHY THIS IS A SEPARATE MODULE FROM objectStorage.js, which already does R2:
// a different bucket and, deliberately, a DIFFERENT TOKEN. objectStorage.js states the rule
// for call recordings ("a separate token from the OTA one on purpose: a leak of either must
// not expose the other") and it applies with more force here. The backups bucket holds every
// customer's mobile, every astrologer's bank account and UPI id, and every chat message ever
// sent — in one file. A token that can read it must not be reachable from a token that only
// needs to serve an OTA bundle. Sharing a client would have quietly shared the credential.
//
// Configuration (VPS backend .env). Until ALL FOUR are set, isConfigured() is false and the
// backup job refuses to run rather than silently keeping backups nowhere:
//   R2_ENDPOINT                 https://<account id>.r2.cloudflarestorage.com  (shared)
//   R2_BACKUP_BUCKET            e.g. astrowani-db-backups
//   R2_BACKUP_ACCESS_KEY_ID     an R2 token scoped to THAT bucket only (Object Read & Write)
//   R2_BACKUP_SECRET_ACCESS_KEY
//
// The token needs Read as well as Write: the job re-downloads what it just uploaded to prove
// the bytes arrived intact, and pruning has to list before it deletes.

const { AwsClient } = require('aws4fetch');

const cfg = () => ({
  endpoint: (process.env.R2_ENDPOINT || '').replace(/\/+$/, ''),
  bucket: process.env.R2_BACKUP_BUCKET || '',
  accessKeyId: process.env.R2_BACKUP_ACCESS_KEY_ID || '',
  secretAccessKey: process.env.R2_BACKUP_SECRET_ACCESS_KEY || '',
});

function isConfigured() {
  const c = cfg();
  return !!(c.endpoint && c.bucket && c.accessKeyId && c.secretAccessKey);
}

/** Which pieces are missing, for an error message that says what to go and set. */
function missingConfig() {
  const c = cfg();
  return [
    !c.endpoint && 'R2_ENDPOINT',
    !c.bucket && 'R2_BACKUP_BUCKET',
    !c.accessKeyId && 'R2_BACKUP_ACCESS_KEY_ID',
    !c.secretAccessKey && 'R2_BACKUP_SECRET_ACCESS_KEY',
  ].filter(Boolean);
}

function client() {
  const c = cfg();
  return new AwsClient({
    accessKeyId: c.accessKeyId,
    secretAccessKey: c.secretAccessKey,
    service: 's3',
    region: 'auto',
  });
}

const objectUrl = (key) => {
  const c = cfg();
  // Encode each segment but keep the slashes: the key's shape is how backups are grouped by
  // run, and an encoded '/' would flatten every run into one unreadable name.
  return `${c.endpoint}/${c.bucket}/${key.split('/').map(encodeURIComponent).join('/')}`;
};

async function put(key, body, contentType = 'application/octet-stream') {
  const res = await client().fetch(objectUrl(key), {
    method: 'PUT',
    body,
    headers: { 'content-type': contentType, 'content-length': String(body.length) },
  });
  if (!res.ok) throw new Error(`backup PUT ${key} failed (${res.status} ${await safeText(res)})`);
}

/** @returns {Promise<{exists:boolean, bytes?:number, etag?:string}>} */
async function head(key) {
  const res = await client().fetch(objectUrl(key), { method: 'HEAD' });
  if (res.status === 404) return { exists: false };
  if (!res.ok) throw new Error(`backup HEAD ${key} failed (${res.status})`);
  return {
    exists: true,
    bytes: Number(res.headers.get('content-length')) || 0,
    etag: (res.headers.get('etag') || '').replace(/"/g, ''),
  };
}

async function getBuffer(key) {
  const res = await client().fetch(objectUrl(key), { method: 'GET' });
  if (!res.ok) throw new Error(`backup GET ${key} failed (${res.status})`);
  return Buffer.from(await res.arrayBuffer());
}

async function remove(key) {
  const res = await client().fetch(objectUrl(key), { method: 'DELETE' });
  // 204 on success; 404 means it is already gone, which is what the caller wanted.
  if (!res.ok && res.status !== 404) throw new Error(`backup DELETE ${key} failed (${res.status})`);
}

/**
 * Every key under `prefix`, following continuation tokens to the end.
 *
 * The XML is picked apart with regexes rather than an XML parser. That is a deliberate
 * trade: it avoids adding a dependency for one response shape generated by a machine, and
 * the fields wanted (Key, Size, ETag, NextContinuationToken) are flat scalars that cannot
 * nest. It would be the wrong call for arbitrary third-party XML; it is fine for this.
 *
 * It DOES stop on a truncated-but-untokened response rather than looping: R2 returning
 * IsTruncated with no token would otherwise spin forever against a paid API.
 *
 * @returns {Promise<Array<{key:string, bytes:number, etag:string}>>}
 */
async function list(prefix) {
  const c = cfg();
  const out = [];
  let token = null;
  for (let page = 0; page < 1000; page += 1) {
    const qs = new URLSearchParams({ 'list-type': '2', prefix, 'max-keys': '1000' });
    if (token) qs.set('continuation-token', token);
    const res = await client().fetch(`${c.endpoint}/${c.bucket}?${qs}`, { method: 'GET' });
    if (!res.ok) throw new Error(`backup LIST ${prefix} failed (${res.status} ${await safeText(res)})`);
    const xml = await res.text();

    for (const block of xml.match(/<Contents>[\s\S]*?<\/Contents>/g) || []) {
      const key = (block.match(/<Key>([\s\S]*?)<\/Key>/) || [])[1];
      if (!key) continue;
      out.push({
        key: decodeXml(key),
        bytes: Number((block.match(/<Size>(\d+)<\/Size>/) || [])[1] || 0),
        etag: ((block.match(/<ETag>([\s\S]*?)<\/ETag>/) || [])[1] || '').replace(/&quot;|"/g, ''),
      });
    }

    const truncated = /<IsTruncated>\s*true\s*<\/IsTruncated>/.test(xml);
    token = (xml.match(/<NextContinuationToken>([\s\S]*?)<\/NextContinuationToken>/) || [])[1] || null;
    if (!truncated || !token) break;
  }
  return out;
}

const decodeXml = (s) =>
  s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'").replace(/&amp;/g, '&');

async function safeText(res) {
  try { return (await res.text()).slice(0, 300); } catch { return ''; }
}

module.exports = { isConfigured, missingConfig, put, head, getBuffer, remove, list };
