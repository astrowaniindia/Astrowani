#!/usr/bin/env node
/**
 * Homepage first paint: inline the first screen's CSS, load the rest without
 * blocking.
 *
 *   node aw/apply-critical-css.js            # rewrite index.html
 *   node aw/apply-critical-css.js --check    # report, write nothing
 *
 * WHY. style.css + aw/aw.css are 111 KB, and as plain <link rel="stylesheet">
 * the browser paints NOTHING until both have downloaded — on Indian mobile data
 * that is most of the homepage's 3.9 s LCP that is not server time (CLAUDE.md
 * EQ5). Now the ~19 KB of rules the first screen uses ship inside the HTML, and
 * the two files load as `preload` and switch on when they arrive.
 *
 * THE CSS IS aw/critical-index.css, extracted in a browser by
 * aw/critical-css-extract.js (its header says how). IT IS A SNAPSHOT: after a
 * change to the homepage's TOP (nav, hero) in style.css or aw.css, re-extract it.
 * A stale copy is not a broken page — the full sheets still load a moment later
 * and win — it is a brief flash of the old look on first paint. Nothing below
 * the first screen depends on it.
 *
 * Only index.html is done (and hi/index.html, which aw/make-hindi-pages.js
 * builds from it). Other pages keep blocking stylesheets: they are reached
 * mostly from the homepage, by which time both files are cached.
 *
 * ORDER (CLAUDE.md EQ1): before make-hindi-pages, so the Hindi homepage gets it.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PAGE = path.join(ROOT, 'index.html');
const CSS = path.join(__dirname, 'critical-index.css');
const START = '<!-- CRITICAL-CSS:START — generated by aw/apply-critical-css.js -->';
const END = '<!-- CRITICAL-CSS:END -->';
const check = process.argv.includes('--check');

// Asset URLs inside the inlined CSS (the self-hosted fonts) carry the same ?h=
// content hash aw/version-images.js puts on them, so the two scripts agree and
// neither undoes the other.
const { rewrite: versionAssets } = require('./version-images.js');
const css = versionAssets(fs.readFileSync(CSS, 'utf8'))
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s*\n\s*/g, '')
  .trim();
if (css.length < 2000 || !/(^|})\s*body\s*\{/.test(css)) {
  console.error('aw/critical-index.css looks wrong (too short, or no body rule) — re-extract it.');
  process.exit(1);
}
if (/<\/style/i.test(css)) { console.error('critical CSS contains </style'); process.exit(1); }

let html = fs.readFileSync(PAGE, 'utf8');
const before = html;
const eol = html.includes('\r\n') ? '\r\n' : '\n';
const block = `${START}${eol}<style>${css}</style>${eol}${END}`;

// 1. The inline block, just before the first site stylesheet.
html = html.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}\\r?\\n?`), '');
const firstLink = html.search(/<link rel="(?:stylesheet|preload)" href="style\.css\?v=\d+"/);
if (firstLink < 0) { console.error('index.html: style.css link not found'); process.exit(1); }
html = `${html.slice(0, firstLink)}${block}${eol}${html.slice(firstLink)}`;

// 2. The two sheets: preload, switch to stylesheet on load; <noscript> for no-JS.
for (const file of ['style\\.css', 'aw\\/aw\\.css']) {
  html = html.replace(new RegExp(`<link rel="stylesheet" href="(${file}\\?v=\\d+)">(?!</noscript>)`), (_, href) =>
    `<link rel="preload" href="${href}" as="style" onload="this.onload=null;this.rel='stylesheet'"><noscript><link rel="stylesheet" href="${href}"></noscript>`);
}

const changed = html !== before;
if (changed && !check) fs.writeFileSync(PAGE, html);
console.log(`${check ? 'would change' : 'changed'}: ${changed ? 1 : 0} page(s); critical CSS ${css.length} bytes`);
