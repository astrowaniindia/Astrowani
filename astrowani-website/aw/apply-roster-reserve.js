#!/usr/bin/env node
/**
 * Reserve the astrologer grid's height, so nothing below it jumps.
 *
 *   node aw/apply-roster-reserve.js           # write the rules into the pages
 *   node aw/apply-roster-reserve.js --check   # report, write nothing
 *
 * WHY THIS EXISTS, AND HOW BAD IT WAS. Measured on a GitHub runner with
 * simulated mobile throttling, 2026-10-30:
 *
 *   consult.html      CLS 0.967
 *   astrologers.html  CLS 0.959
 *
 * The Core Web Vitals target is 0.1. Both grids ship EMPTY — the HTML holds a
 * comment where the cards go — and script.js fills them from
 * astrologers-data.js once 119KB of JavaScript has downloaded and parsed. Until
 * then the grid is zero pixels tall, so the moment the cards appear everything
 * below is shoved down by the full height of the roster: over 23,000px at phone
 * width.
 *
 * THE REASON NOBODY SAW IT. On a fast connection the script arrives before the
 * first paint and the measured CLS is exactly 0 — confirmed in a real browser
 * against the live site. It only appears under throttling, which is to say: it
 * only appears for the people actually using the site on Indian mobile data,
 * and never for anyone testing it on wifi.
 *
 * WHY min-height AND NOT SKELETON CARDS. Card heights are content-driven and
 * vary (330-397px measured), so placeholder cards would have to guess each
 * one's height and would shift anyway when the real card turned out different.
 * A min-height on the container only has to be approximately right, and it
 * costs three CSS rules rather than 54 elements of markup.
 *
 * AND WHY IT LEAVES NO GAP: min-height applies only while the content is
 * SHORTER than it. The moment the real cards render the grid is taller than the
 * reserve, so the value stops mattering entirely. Over-reserving slightly is
 * therefore free; under-reserving leaves a small downward push, far below the
 * fold, where it is not visible and does not count toward CLS.
 *
 * THE NUMBERS BELOW ARE MEASURED, NOT GUESSED. Card heights were read off the
 * live site at three viewports (1440px/4 columns, 700px/2, 375px/1) and the row
 * gap is the computed `row-gap`. Re-run this script when the roster snapshot
 * changes — it recounts from astrologers-data.js — and re-measure the heights
 * if the card's markup changes.
 */

const fs = require('fs');
const path = require('path');

const SITE = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');

/** Measured on the live site, 2026-10-30. Card height is content-driven, so it
 *  barely changes between 4 and 2 columns and grows when a card goes full width. */
const CARD_HEIGHT = { 4: 338, 2: 337, 1: 370 };
const ROW_GAP = 24;

/** The breakpoints each page already declares for its own grid. */
const BREAKPOINTS = [
  { columns: 4, media: null },
  { columns: 2, media: '(max-width:900px)' },
  { columns: 1, media: '(max-width:560px)' },
];

const GRIDS = [
  { file: 'consult.html', id: 'astro-consult-grid' },
  { file: 'astrologers.html', id: 'astro-directory-grid' },
];

const START = '<style data-roster-reserve>';
const END = '</style><!-- /roster-reserve -->';

/** How many cards the FIRST render puts on the page — the bundled snapshot, not
 *  the live roster that replaces it a moment later. */
function snapshotCount() {
  const src = fs.readFileSync(path.join(SITE, 'astrologers-data.js'), 'utf8');
  // Counted rather than parsed: the file is a JS literal with unquoted keys, so
  // JSON.parse refuses it, and a count cannot be broken by a trailing comma.
  // One astrologer per line, each starting `{ id: '...'`.
  const n = (src.match(/^\s*\{\s*id:/gm) || []).length;
  if (!n) throw new Error('astrologers-data.js: found no entries to count');
  return n;
}

function reserveFor(count, columns) {
  const rows = Math.ceil(count / columns);
  return rows * CARD_HEIGHT[columns] + (rows - 1) * ROW_GAP;
}

function blockFor(id, count) {
  const lines = [
    `${START}`,
    `/* Generated by aw/apply-roster-reserve.js — ${count} astrologers in the snapshot.`,
    `   Stops the page below the grid jumping when the cards render; see that file. */`,
  ];
  for (const bp of BREAKPOINTS) {
    const rule = `#${id} { min-height: ${reserveFor(count, bp.columns)}px; }`;
    lines.push(bp.media ? `@media ${bp.media} { ${rule} }` : rule);
  }
  lines.push(END);
  return lines.join('\n');
}

const count = snapshotCount();
let changed = 0;

for (const grid of GRIDS) {
  const file = path.join(SITE, grid.file);
  const before = fs.readFileSync(file, 'utf8');
  // These pages are checked out with CRLF. Building the block with the file's
  // own endings is what makes a second run a genuine no-op rather than a
  // whole-block rewrite that reports a change every time.
  const nl = before.includes('\r\n') ? '\r\n' : '\n';
  const block = blockFor(grid.id, count).split('\n').join(nl);

  let after;
  if (before.includes(START)) {
    const from = before.indexOf(START);
    const to = before.indexOf(END, from) + END.length;
    after = before.slice(0, from) + block + before.slice(to);
  } else {
    // Right after the grid's own closing tags, so the rule sits next to the
    // element it is about rather than in a stylesheet shared by every page.
    const anchor = `<div id="${grid.id}"`;
    const start = before.indexOf(anchor);
    if (start === -1) throw new Error(`${grid.file}: no ${anchor}`);
    // Line-ending agnostic on purpose: these pages are checked out with CRLF,
    // and matching a literal "\n" here silently found nothing.
    const close = /<\/div>\s*<\/div>\s*<\/div>/.exec(before.slice(start));
    if (!close) throw new Error(`${grid.file}: could not find the grid's closing tags`);
    const at = start + close.index + close[0].length;
    after = before.slice(0, at) + nl + block + before.slice(at);
  }

  if (after !== before) {
    changed += 1;
    console.log(`  ${check ? 'would update' : 'updated'}  ${grid.file}  (#${grid.id})`);
    if (!check) fs.writeFileSync(file, after);
  }
}

for (const bp of BREAKPOINTS) {
  console.log(`  ${bp.columns} column(s): ${Math.ceil(count / bp.columns)} rows → ${reserveFor(count, bp.columns)}px`);
}
console.log(`${check ? 'would change' : 'changed'}: ${changed} page(s), from ${count} astrologers in the snapshot.`);
