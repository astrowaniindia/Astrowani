#!/usr/bin/env node
/**
 * Generate one page per instant calculator.
 *
 *   node aw/calculator-pages.js            # write the pages + merge the Hindi
 *   node aw/calculator-pages.js --check    # report, write nothing
 *
 * ============================================================================
 * WHY THESE EXIST.
 *
 * Twelve working calculators lived on ONE url, calculators.html, reached by
 * fragments — calculators.html#love, #numerology, #rashi. Google strips a
 * fragment entirely, so to a crawler those were all the same page with one
 * title and one H1, and "love calculator", "numerology calculator", "rashi
 * calculator" had nowhere to rank. Calculator pages are the highest-volume
 * page type in this niche (MD files/SEO-Growth-Gap-Analysis-2026-10-30.md, 1.1).
 *
 * WHAT IS AND IS NOT HERE. Only the twelve calculators that really compute
 * something in the browser. The eight "needs a full birth chart" entries
 * (dasha, mangal dosha, sade sati, ...) stay as tiles on calculators.html: a
 * page whose whole content is "ask an astrologer" is thin content, which is
 * exactly what Google's scaled-content systems demote.
 *
 * THE CARD IS LIFTED FROM calculators.html AT BUILD TIME, not copied into
 * this file. Its markup, ids and Hindi strings already exist and already work,
 * and one source means the calculator on its own page and on the index page
 * can never drift. The wiring is shared too: aw/calculators-wire.js.
 *
 * Each page's copy is in aw/calculator-pages-content.js with its Hindi beside
 * it; this script merges those pairs into aw/hindi-strings.json, so the /hi/
 * versions build from the same run.
 * ============================================================================
 *
 * ORDER (see CLAUDE.md EQ1): run this, then bump-version, make-hindi-pages,
 * apply-seo — the Hindi pages are built FROM these, and the SEO block is added
 * last.
 */

const { fitTitle } = require('./seo-title');
const fs = require('fs');
const path = require('path');
const { SHARED, PAGES } = require('./calculator-pages-content.js');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'calculators.html');
const STRINGS = path.join(__dirname, 'hindi-strings.json');
const MARK = '<!-- generated by aw/calculator-pages.js -->';
const check = process.argv.includes('--check');

const en = (pair) => pair[0];

/** The calculator card with the given id, by counting <div> depth. */
function liftCard(html, id) {
  const open = `<div class="calc-card" id="${id}">`;
  const start = html.indexOf(open);
  if (start < 0) throw new Error(`calc card #${id} not found in calculators.html`);
  const re = /<\/?div\b[^>]*>/g;
  re.lastIndex = start;
  let depth = 0;
  let m;
  while ((m = re.exec(html)) !== null) {
    depth += m[0].startsWith('</') ? -1 : 1;
    if (depth === 0) {
      return html.slice(start, re.lastIndex)
        // On its own page the title is not a link to the page it is on.
        .replace(/(<div class="calc-card-title">)<a [^>]*>([\s\S]*?)<\/a>/, '$1$2');
    }
  }
  throw new Error(`calc card #${id} is not closed`);
}

function body(p, card) {
  const prose = p.sections.map(([h, ...paras]) => `
<div class="band">
  <div class="block" style="max-width:760px;">
    <h2 class="serif section-title" style="margin-bottom:22px;">${en(h)}</h2>
    ${paras.map((t) => `<p style="font-size:15.5px; line-height:1.85; color:var(--ink-soft); margin:0 0 18px;">${en(t)}</p>`).join('\n    ')}
  </div>
</div>`).join('\n');

  // h3 + p: the shape apply-seo.js reads to build FAQPage from what is visible.
  const faqs = `
<div class="band band-tint">
  <div class="block" style="max-width:760px;">
    <div class="eyebrow">${en(SHARED.faqEyebrow)}</div>
    <h2 class="serif section-title" style="margin-bottom:26px;">${en(SHARED.faqTitle)}</h2>
    ${p.faqs.map(([q, a]) => `<div style="margin:0 0 24px;">
      <h3 style="font-size:17px; margin:0 0 8px; color:var(--maroon);">${en(q)}</h3>
      <p style="font-size:15.5px; line-height:1.8; color:var(--ink-soft); margin:0;">${en(a)}</p>
    </div>`).join('\n    ')}
  </div>
</div>`;

  // Static links, not script-rendered chips: these are what a crawler follows
  // from one calculator to the next.
  const others = PAGES.filter((o) => o.file !== p.file).map((o) =>
    `      <a class="tool-index-chip" href="${o.file}">${o.crumb}</a>`).join('\n');

  return `<main id="content">
<div class="page-header">
  <div class="crumb"><a href="index.html" style="color:var(--gold);">Home</a> · <a href="calculators.html" style="color:var(--gold);">${en(SHARED.crumbParent)}</a> · ${p.crumb}</div>
  <h1 class="serif">${en(p.h1)}</h1>
  <p>${en(p.lead)}</p>
</div>

<div class="band">
  <div class="block" style="max-width:760px;">
    ${card}
  </div>
</div>
${prose}
${faqs}

<div class="band">
  <div class="block">
    <h2 class="serif section-title" style="margin-bottom:24px;">${en(SHARED.moreTitle)}</h2>
    <div class="tool-index-grid">
${others}
    </div>
    <p style="margin:22px 0 0;"><a href="calculators.html" style="color:var(--maroon); font-weight:700;">${en(SHARED.seeAll)}</a></p>
  </div>
</div>

<div class="band band-tint">
  <div class="block" style="max-width:720px; text-align:center;">
    <h2 class="serif section-title" style="margin-bottom:18px;">${en(SHARED.ctaTitle)}</h2>
    <p style="font-size:15.5px; line-height:1.75; color:var(--ink-soft); margin:0 0 30px;">${en(SHARED.ctaText)}</p>
    <a href="consult.html?mode=chat" class="btn-gold magnetic" style="display:inline-block; font-size:16px; padding:16px 34px;">${en(SHARED.ctaButton)}</a>
    <p style="margin:22px 0 0; font-size:14.5px; color:var(--ink-soft);"><span>${en(SHARED.ctaOr)}</span> <a href="${p.related[0]}" style="color:var(--maroon); font-weight:700;">${p.related[1]}</a></p>
  </div>
</div>

</main>`;
}

/** Every [en, hi] pair this file owns. Needs p.crumb, so runs after it is read. */
function pairs(dict) {
  const out = [...Object.values(SHARED)];
  for (const p of PAGES) {
    // The <title>, and the breadcrumb's last text node ("· Love Calculator"),
    // which the walker sees as one string separate from the links before it.
    out.push([p.title, p.titleHi], [`· ${p.crumb}`, `· ${dict[p.crumb]}`]);
    out.push(p.h1, p.lead);
    for (const [h, ...paras] of p.sections) out.push(h, ...paras);
    for (const [q, a] of p.faqs) out.push(q, a);
  }
  return out;
}

if (require.main === module) {
  const src = fs.readFileSync(SOURCE, 'utf8');
  const eol = src.includes('\r\n') ? '\r\n' : '\n';
  const headEnd = src.indexOf('<main id="content">');
  const footStart = src.indexOf('<footer');
  if (headEnd < 0 || footStart < 0) {
    console.error('could not find <main> / <footer> in calculators.html — template shape changed.');
    process.exit(1);
  }
  // Its own SEO block and title belong to calculators.html; apply-seo writes ours.
  const chromeTop = src.slice(0, headEnd).replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->\r?\n?/, '');
  const chromeBottom = src.slice(footStart);
  if (!chromeBottom.includes('aw/calculators-wire.js')) {
    console.error('calculators.html no longer loads aw/calculators-wire.js — the pages would not work.');
    process.exit(1);
  }

  const dict = JSON.parse(fs.readFileSync(STRINGS, 'utf8'));
  for (const p of PAGES) {
    p.crumb = (src.match(new RegExp(`<div class="calc-card" id="${p.id}">\\s*<div class="calc-card-title">(?:<a [^>]*>)?([^<]+)`)) || [])[1];
    if (!p.crumb) { console.error(`no title for #${p.id}`); process.exit(1); }
    if (!dict[p.related[1]]) { console.error(`related label "${p.related[1]}" has no Hindi`); process.exit(1); }
    if (!fs.existsSync(path.join(ROOT, p.related[0]))) { console.error(`related page ${p.related[0]} missing`); process.exit(1); }
  }

  // ── Hindi ── never silently overwrite a translation somebody else owns.
  let added = 0;
  const conflicts = [];
  for (const [e, h] of pairs(dict)) {
    if (!h || h.includes('undefined')) { console.error(`no Hindi for: ${e}`); process.exit(1); }
    if (dict[e] === undefined) { dict[e] = h; added++; }
    else if (dict[e] !== h) conflicts.push(e);
  }
  if (conflicts.length) {
    console.error('These English strings already have a DIFFERENT Hindi translation in hindi-strings.json.');
    console.error('Use that translation in calculator-pages-content.js, or change it there deliberately:');
    for (const c of conflicts) console.error(`  ${JSON.stringify(c)}`);
    process.exit(1);
  }

  let wrote = 0;
  for (const p of PAGES) {
    const card = liftCard(src, p.id).split('\r\n').join('\n');
    const top = chromeTop.replace(/<title>[\s\S]*?<\/title>/, `<title>${fitTitle(p.title).replace(/&(?!amp;)/g, '&amp;')}</title>`);
    let html = top + body(p, card) + '\n\n' + chromeBottom;
    html = html.split('\r\n').join('\n').replace('<body>', `<body>\n${MARK}`).split('\n').join(eol);
    const out = path.join(ROOT, p.file);
    const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (prev && !prev.includes(MARK)) {
      console.error(`REFUSING to overwrite ${p.file}: it exists and was not generated here.`);
      process.exit(1);
    }
    // apply-seo has already added a block to a previous run's output; compare without it.
    // Line endings are ignored too: apply-seo writes a bare \n after <title>, so
    // comparing raw bytes reported every page as changed on every run.
    const norm = (s) => s.replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->\r?\n?/, '').replace(/\r/g, '');
    if (!prev || norm(prev) !== norm(html)) {
      wrote++;
      if (!check) fs.writeFileSync(out, html);
      console.log(`${check ? 'would write' : 'wrote'}  ${p.file}`);
    }
  }
  if (!check && added) fs.writeFileSync(STRINGS, JSON.stringify(dict, null, 2) + '\n');
  console.log(`\n${check ? 'would write' : 'wrote'} ${wrote} page(s); ${added} new Hindi string(s)`);
  if (wrote) console.log('NOW RUN: bump-version, make-hindi-pages, apply-seo (in that order)');
}

module.exports.PAGES = PAGES;
