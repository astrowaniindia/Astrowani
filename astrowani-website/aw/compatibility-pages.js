#!/usr/bin/env node
/**
 * Generate the zodiac compatibility pages: one per pair of signs (78) and the
 * compatibility.html hub that links to all of them.
 *
 *   node aw/compatibility-pages.js            # write pages + Hindi strings
 *   node aw/compatibility-pages.js --check    # report, write nothing
 *
 * ============================================================================
 * WHY. "aries and taurus compatibility" / "mesh vrishabh rashi milan" style
 * searches had nowhere to land (SEO-Growth-Gap-Analysis-2026-10-30). What each
 * page says, and why no two say the same thing, is in the header of
 * aw/compatibility-pages-content.js — read that before changing the copy.
 *
 * Every visible string goes through t([en, hi]), which both returns the
 * English and records the pair for hindi-strings.json, so nothing on a page
 * can be missed by the Hindi build.
 *
 * ORDER (CLAUDE.md EQ1): run this, then bump-version, make-hindi-pages,
 * apply-seo. The page chrome (head, nav, footer) is lifted from horoscope.html.
 * ============================================================================
 */

const { fitTitle } = require('./seo-title');
const fs = require('fs');
const path = require('path');
const { SHARED, SIGNS, PAIRS, pairsOf } = require('./compatibility-pages-content.js');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'horoscope.html');
const STRINGS = path.join(__dirname, 'hindi-strings.json');
const MARK = '<!-- generated by aw/compatibility-pages.js -->';
const HUB = 'compatibility.html';
const check = process.argv.includes('--check');

const seen = [];
const t = (pair) => { seen.push(pair); return pair[0]; };
const P = 'style="font-size:15.5px; line-height:1.85; color:var(--ink-soft); margin:0 0 18px;"';
const H2 = (txt, first) => `<h2 class="serif section-title" style="margin:${first ? '0' : '34px'} 0 18px;">${txt}</h2>`;

const chip = (p, current) => (p === current ? '' : `      <a class="tool-index-chip" href="${p.file}">${t(p.label)}</a>`);
const chips = (list, current) => list.map((p) => chip(p, current)).filter(Boolean).join('\n');

function fact(label, value) {
  return `      <div style="padding:14px 0; border-bottom:1px solid var(--line, rgba(89,42,25,.15));"><div style="font-size:13px; color:var(--ink-soft);">${t(label)}</div><div style="font-size:16px; font-weight:700; color:var(--maroon);">${t(value)}</div></div>`;
}

function crumb(last) {
  // The trail apply-seo.js turns into BreadcrumbList. The text node after the
  // last link is " · <name>", so that is what is registered for Hindi.
  t([`· ${last[0]}`, `· ${last[1]}`]);
  return `  <div class="crumb"><a href="index.html" style="color:var(--gold);">Home</a> · <a href="${HUB}" style="color:var(--gold);">${t(SHARED.crumbParent)}</a> · ${last[0]}</div>`;
}

function pairBody(p) {
  const { A, B } = p;
  const more = (S) => `    ${H2(t([`More ${S.name} pairings`, `${S.hi} की और जोड़ियां`]), false)}
    <div class="tool-index-grid">
${chips(pairsOf(S), p)}
    </div>`;
  const horoscopes = (A === B ? [A] : [A, B]).map((S) =>
    `<a href="${S.file}" style="color:var(--maroon); font-weight:700;">${t([`${S.name} horoscope`, `${S.hi} राशिफल`])}</a>`).join(' <span style="margin:0 8px;">·</span> ');

  return `<main id="content">
<div class="page-header">
${crumb(p.crumb)}
  <h1 class="serif">${t(p.h1)}</h1>
  <p>${t(p.lead)}</p>
</div>

<div class="band band-tint">
  <div class="block" style="max-width:760px;">
    ${H2(t(SHARED.glanceTitle), true)}
    <div>
${Object.keys(SHARED.facts).map((k) => fact(SHARED.facts[k], p.facts[k])).join('\n')}
    </div>
    <p style="margin:22px 0 0;">${horoscopes}</p>
  </div>
</div>

<div class="band">
  <div class="block" style="max-width:760px;">
    ${H2(t(p.elementsTitle), true)}
    <p ${P}>${t(p.elements)}</p>
    ${H2(t(SHARED.modesTitle), false)}
    <p ${P}>${t(p.modes)}</p>
    ${H2(t(SHARED.lordsTitle), false)}
    <p ${P}>${t(p.lords)}</p>
    ${H2(t(SHARED.placeTitle), false)}
    <p ${P}>${t(p.place)}</p>
    ${H2(t(SHARED.bringsTitle), false)}
    <p ${P}>${t(p.brings)}</p>
  </div>
</div>

<div class="band band-tint">
  <div class="block" style="max-width:760px;">
    ${H2(t(SHARED.limitsTitle), true)}
    <p ${P}>${t(SHARED.limitsText)}</p>
    <p style="margin:0;"><a href="marriage.html" style="color:var(--maroon); font-weight:700;">${t(SHARED.matchLink)}</a> <span style="margin:0 8px;">·</span> <a href="rashi-calculator.html" style="color:var(--maroon); font-weight:700;">${t(SHARED.rashiLink)}</a></p>
  </div>
</div>

<div class="band">
  <div class="block" style="max-width:760px;">
    <div class="eyebrow">${t(SHARED.faqEyebrow)}</div>
    <h2 class="serif section-title" style="margin-bottom:26px;">${t(SHARED.faqTitle)}</h2>
    ${p.faqs.map(([q, a]) => `<div style="margin:0 0 24px;">
      <h3 style="font-size:17px; margin:0 0 8px; color:var(--maroon);">${t(q)}</h3>
      <p style="font-size:15.5px; line-height:1.8; color:var(--ink-soft); margin:0;">${t(a)}</p>
    </div>`).join('\n    ')}
  </div>
</div>

<div class="band band-tint">
  <div class="block">
${more(A)}
${A === B ? '' : more(B)}
    <p style="margin:22px 0 0;"><a href="${HUB}" style="color:var(--maroon); font-weight:700;">${t(SHARED.allLink)}</a></p>
  </div>
</div>

${cta()}

</main>`;
}

function cta() {
  return `<div class="band">
  <div class="block" style="max-width:720px; text-align:center;">
    <h2 class="serif section-title" style="margin-bottom:18px;">${t(SHARED.ctaTitle)}</h2>
    <p style="font-size:15.5px; line-height:1.75; color:var(--ink-soft); margin:0 0 30px;">${t(SHARED.ctaText)}</p>
    <a href="consult.html?mode=chat" class="btn-gold magnetic" style="display:inline-block; font-size:16px; padding:16px 34px;">${t(SHARED.ctaButton)}</a>
  </div>
</div>`;
}

function hubBody() {
  const h = SHARED.hub;
  t([`· ${SHARED.crumbParent[0]}`, `· ${SHARED.crumbParent[1]}`]);
  return `<main id="content">
<div class="page-header">
  <div class="crumb"><a href="index.html" style="color:var(--gold);">Home</a> · ${SHARED.crumbParent[0]}</div>
  <h1 class="serif">${t(h.h1)}</h1>
  <p>${t(h.lead)}</p>
</div>

<div class="band">
  <div class="block" style="max-width:760px;">
    ${H2(t(h.introTitle), true)}
    <p ${P}>${t(h.intro)}</p>
    <p ${P}>${t(SHARED.limitsText)}</p>
  </div>
</div>

<div class="band band-tint">
  <div class="block">
${SIGNS.map((S, i) => `    ${H2(t(h.bySign(S)), i === 0)}
    <div class="tool-index-grid">
${chips(pairsOf(S), null)}
    </div>`).join('\n')}
  </div>
</div>

${cta()}

</main>`;
}

if (require.main === module) {
  const src = fs.readFileSync(SOURCE, 'utf8');
  const eol = src.includes('\r\n') ? '\r\n' : '\n';
  const headEnd = src.indexOf('<main id="content">');
  const footStart = src.indexOf('<footer');
  if (headEnd < 0 || footStart < 0) { console.error('horoscope.html: template shape changed'); process.exit(1); }
  const chromeTop = src.slice(0, headEnd).replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->\r?\n?/, '');
  // horoscope.html's own inline reading script has no business on these pages.
  const inline = /<script>\s*document\.addEventListener\('DOMContentLoaded'[\s\S]*?<\/script>\r?\n?/;
  const chromeBottom = src.slice(footStart).replace(inline, '');

  const pages = [...PAIRS.map((p) => ({ file: p.file, title: p.title, titleHi: p.titleHi, body: pairBody(p) })),
    { file: HUB, title: SHARED.hub.title, titleHi: SHARED.hub.titleHi, body: hubBody() }];
  for (const pg of pages) t([pg.title, pg.titleHi]);

  // ── Hindi ── never silently overwrite a translation somebody else owns.
  const dict = JSON.parse(fs.readFileSync(STRINGS, 'utf8'));
  let added = 0;
  const conflicts = [];
  const mine = new Map();
  for (const [e, h] of seen) {
    if (!h || /undefined|NaN/.test(e + h)) { console.error(`bad pair: ${e} / ${h}`); process.exit(1); }
    if (mine.has(e) && mine.get(e) !== h) { console.error(`one English string, two Hindi: ${e}`); process.exit(1); }
    mine.set(e, h);
  }
  for (const [e, h] of mine) {
    if (dict[e] === undefined) { dict[e] = h; added++; } else if (dict[e] !== h) conflicts.push(`${JSON.stringify(e)}  has "${dict[e]}", wanted "${h}"`);
  }
  if (conflicts.length) {
    console.error('These English strings already have a DIFFERENT Hindi translation in hindi-strings.json:');
    for (const c of conflicts) console.error(`  ${c}`);
    process.exit(1);
  }

  let wrote = 0;
  for (const pg of pages) {
    const top = chromeTop.replace(/<title>[\s\S]*?<\/title>/, `<title>${fitTitle(pg.title)}</title>`);
    const html = (top + pg.body + '\n\n' + chromeBottom).split('\r\n').join('\n')
      .replace('<body>', `<body>\n${MARK}`).split('\n').join(eol);
    const out = path.join(ROOT, pg.file);
    const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (prev && !prev.includes(MARK)) { console.error(`REFUSING to overwrite ${pg.file}: not generated here.`); process.exit(1); }
    const norm = (x) => x.replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->\r?\n?/, '').replace(/\r/g, '');
    if (!prev || norm(prev) !== norm(html)) {
      wrote++;
      if (!check) fs.writeFileSync(out, html);
    }
  }
  if (!check && added) {
    const crlf = fs.readFileSync(STRINGS, 'utf8').includes('\r\n');
    const text = JSON.stringify(dict, null, 2) + '\n';
    fs.writeFileSync(STRINGS, crlf ? text.replace(/\n/g, '\r\n') : text);
  }
  console.log(`${check ? 'would write' : 'wrote'} ${wrote} page(s); ${added} new Hindi string(s)`);
  if (wrote) console.log('NOW RUN: bump-version, make-hindi-pages, apply-seo (in that order)');
}

module.exports = { PAIRS, HUB, files: () => [...PAIRS.map((p) => p.file), HUB] };
