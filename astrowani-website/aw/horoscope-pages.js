/** The static sign links on horoscope.html — what a crawler follows to reach the pages. */
function hubBlock() {
  return `${LINKS_START}
<div class="band">
  <div class="block">
    <h2 class="serif section-title" style="margin-bottom:24px;">${en(SHARED.bySignTitle)}</h2>
    <div class="tool-index-grid">
${signLinks(null)}
    </div>
  </div>
</div>
${LINKS_END}`;
}

function pairs(dict) {
  const out = [SHARED.crumbParent, ...Object.values(SHARED.periods), ...Object.values(SHARED.meters),
    SHARED.readingNote, SHARED.factsTitle, ...Object.values(SHARED.facts), SHARED.whichSignTitle,
    SHARED.whichSignText, SHARED.rashiLink, SHARED.sunLink, SHARED.faqEyebrow, SHARED.faqTitle,
    SHARED.otherTitle, SHARED.allLink, COMPAT_ALL, SHARED.ctaTitle, SHARED.ctaText, SHARED.ctaButton, SHARED.bySignTitle];
  for (const s of SIGNS) {
    out.push([s.title, s.titleHi], s.crumb, [`· ${en(s.crumb)}`, `· ${s.crumb[1]}`], s.h1, s.lead,
      s.natureTitle, s.nature, s.lifeTitle, s.life, s.linkLabel, s.element, s.lord, s.day, s.dates, s.partners);
    for (const [q, a] of s.faqs) out.push(q, a);
    out.push(COMPAT_TITLE(s), ...compatOf(s).map((p) => p.label), STORY_LINK(s));
  }
  return out;
}

if (require.main === module) {
  let src = fs.readFileSync(SOURCE, 'utf8');
  const eol = src.includes('\r\n') ? '\r\n' : '\n';

  // ── The hub links on horoscope.html, idempotent between markers. ──
  const block = hubBlock().split('\n').join(eol);
  let hub;
  if (src.includes(LINKS_START)) {
    hub = src.replace(new RegExp(`${LINKS_START}[\\s\\S]*?${LINKS_END}`), () => block);
  } else {
    const anchor = '<section class="landing-guide"';
    if (!src.includes(anchor)) { console.error('horoscope.html: no landing-guide section to insert the links before'); process.exit(1); }
    hub = src.replace(anchor, () => `${block}${eol}${eol}${anchor}`);
  }
  if (hub !== src) {
    if (!check) fs.writeFileSync(SOURCE, hub);
    console.log(`${check ? 'would update' : 'updated'}  horoscope.html (sign links)`);
    src = hub;
  }

  const headEnd = src.indexOf('<main id="content">');
  const footStart = src.indexOf('<footer');
  if (headEnd < 0 || footStart < 0) { console.error('horoscope.html: template shape changed'); process.exit(1); }
  const chromeTop = src.slice(0, headEnd).replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->\r?\n?/, '');
  // horoscope.html's own inline script drives ITS card; the sign pages use aw/horoscope-sign.js.
  let chromeBottom = src.slice(footStart);
  const inline = /<script>\s*document\.addEventListener\('DOMContentLoaded'[\s\S]*?<\/script>\r?\n?/;
  if (!inline.test(chromeBottom)) { console.error('horoscope.html: inline reading script not found'); process.exit(1); }
  const version = (chromeBottom.match(/script\.js\?v=(\d+)/) || [])[1] || '1';
  chromeBottom = chromeBottom.replace(inline, () => `<script src="aw/horoscope-sign.js?v=${version}"></script>${eol}`);
  if (!/astro-engine\.js/.test(chromeBottom)) { console.error('horoscope.html no longer loads astro-engine.js'); process.exit(1); }

  // ── Hindi ── never silently overwrite a translation somebody else owns.
  const dict = JSON.parse(fs.readFileSync(STRINGS, 'utf8'));
  let added = 0;
  const conflicts = [];
  for (const [e, h] of pairs(dict)) {
    if (!h || h.includes('undefined')) { console.error(`no Hindi for: ${e}`); process.exit(1); }
    if (dict[e] === undefined) { dict[e] = h; added++; } else if (dict[e] !== h) conflicts.push(`${JSON.stringify(e)}  has "${dict[e]}", wanted "${h}"`);
  }
  if (conflicts.length) {
    console.error('These English strings already have a DIFFERENT Hindi translation in hindi-strings.json:');
    for (const c of conflicts) console.error(`  ${c}`);
    process.exit(1);
  }

  let wrote = 0;
  for (const s of SIGNS) {
    const top = chromeTop.replace(/<title>[\s\S]*?<\/title>/, `<title>${fitTitle(s.title)}</title>`);
    let html = (top + body(s) + '\n\n' + chromeBottom).split('\r\n').join('\n')
      .replace('<body>', `<body>\n${MARK}`).split('\n').join(eol);
    const out = path.join(ROOT, s.file);
    const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (prev && !prev.includes(MARK)) { console.error(`REFUSING to overwrite ${s.file}: not generated here.`); process.exit(1); }
    const norm = (x) => x.replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->\r?\n?/, '').replace(/\r/g, '');
    if (!prev || norm(prev) !== norm(html)) {
      wrote++;
      if (!check) fs.writeFileSync(out, html);
      console.log(`${check ? 'would write' : 'wrote'}  ${s.file}`);
    }
  }
  if (!check && added) fs.writeFileSync(STRINGS, JSON.stringify(dict, null, 2) + '\n');
  console.log(`\n${check ? 'would write' : 'wrote'} ${wrote} page(s); ${added} new Hindi string(s)`);
  if (wrote) console.log('NOW RUN: bump-version, make-hindi-pages, apply-seo (in that order)');
}

module.exports.SIGNS = SIGNS;
