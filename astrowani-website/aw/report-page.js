#!/usr/bin/env node
/**
 * Generate what-india-asks-an-astrologer.html — an anonymised report on real
 * Astrowani consultations, made to be cited (SEO-Growth-Gap-Analysis 1.13:
 * original data is what still earns links).
 *
 *   node aw/report-page.js            # write the page + Hindi strings
 *   node aw/report-page.js --check    # report, write nothing
 *
 * The numbers are in aw/report-data.js (a dated snapshot; how it was pulled is
 * in WEBSITE.md). Every visible string goes through t([en, hi]) so the Hindi
 * build cannot miss one.
 *
 * ============================================================================
 * APPROVED = false UNTIL THE OWNER SIGNS IT OFF. While false the page is
 * noindex, carries no Dataset markup, is not in the sitemap and is linked from
 * nowhere — it can be read at its address, and that is all. Publishing real
 * customer statistics is the owner's call, not the code's. To publish: set
 * APPROVED = true, re-run this + the usual chain (CLAUDE.md EQ1), and add the
 * page to STATIC_PAGES in astrowani-backend/src/blogSitemap.js.
 *
 * PRIVACY is enforced here, not trusted to the data file: a row under
 * MIN_GROUP is dropped wherever it appears, and its absence is footnoted.
 * ============================================================================
 *
 * ORDER (CLAUDE.md EQ1): run this, then bump-version, make-hindi-pages, apply-seo.
 */
const fs = require('fs');
const path = require('path');
const D = require('./report-data.js');

const APPROVED = false;
const FILE = 'what-india-asks-an-astrologer.html';
const TITLE = ['What India Asks an Astrologer: 2,330 Consultations | Astrowani', 'भारत ज्योतिषी से क्या पूछता है: 2,330 परामर्श | Astrowani'];
const DESC = 'What 2,330 real Astrowani consultations show: love and marriage lead, 90% type in Hinglish, 7 in 10 are women, and the busiest hour is noon. Anonymised data.';

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'horoscope.html');
const STRINGS = path.join(__dirname, 'hindi-strings.json');
const MARK = '<!-- generated by aw/report-page.js -->';
const check = process.argv.includes('--check');

const seen = [];
const t = (pair) => { seen.push(pair); return pair[0]; };
const fmt = (n) => Number(n).toLocaleString('en-IN');
const pct = (n, base) => Math.round((n / base) * 100);
const P = 'style="font-size:15.5px; line-height:1.85; color:var(--ink-soft); margin:0 0 18px;"';
const H2 = (txt, first) => `<h2 class="serif section-title" style="margin:${first ? '0' : '38px'} 0 18px;">${txt}</h2>`;

let dropped = false;
const keep = (rows) => rows.filter((r) => (r.n >= D.MIN_GROUP ? true : (dropped = true, false)));

/** Horizontal bars: label, bar, "35% · 175". Groups under MIN_GROUP are dropped. */
function bars(rows, base) {
  const list = keep(rows);
  const max = Math.max(...list.map((r) => r.n));
  return `<div class="aw-report-bars" style="display:grid; gap:12px; margin:0 0 10px;">
${list.map((r) => `      <div>
        <div style="display:flex; justify-content:space-between; gap:12px; font-size:15px; margin-bottom:5px;"><span style="color:var(--maroon); font-weight:700;">${t(r.label)}</span><span style="color:var(--ink-soft); white-space:nowrap;">${pct(r.n, base)}% · ${fmt(r.n)}</span></div>
        <div style="height:10px; border-radius:5px; background:var(--band-tint);"><div style="height:10px; border-radius:5px; width:${Math.max(2, Math.round((r.n / max) * 100))}%; background:var(--gold-deep);"></div></div>
      </div>`).join('\n')}
    </div>`;
}

function hourChart() {
  const max = Math.max(...D.hours);
  const peak = D.hours.indexOf(max);
  const label = t([`Consultations by hour of the day, India time. The busiest hour is ${peak}:00 to ${peak + 1}:00.`,
    `दिन के हर घंटे में परामर्श, भारतीय समय। सबसे व्यस्त घंटा ${peak}:00 से ${peak + 1}:00 है।`]);
  return `<div role="img" aria-label="${label}" style="display:flex; align-items:flex-end; gap:3px; height:150px; padding:0 2px; border-bottom:1px solid var(--border-soft);">
${D.hours.map((n) => `      <div style="flex:1; height:${Math.max(3, Math.round((n / max) * 100))}%; background:var(--gold-deep); border-radius:3px 3px 0 0;"></div>`).join('\n')}
    </div>
    <div style="display:flex; justify-content:space-between; font-size:12px; color:var(--ink-soft); margin:6px 2px 0;"><span>00:00</span><span>06:00</span><span>12:00</span><span>18:00</span><span>23:00</span></div>`;
}

