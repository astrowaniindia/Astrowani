    <p style="font-size:15.5px; line-height:1.85; color:var(--maroon); margin:0;"><strong>${t(['Using this data:', 'इस डेटा का उपयोग:'])}</strong> ${t(['you are welcome to quote these figures, with a link to this page.', 'आप इन आंकड़ों को इस पेज के लिंक के साथ उद्धृत कर सकते हैं।'])}</p>
